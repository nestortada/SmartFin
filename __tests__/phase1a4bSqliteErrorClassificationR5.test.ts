// Part 3: v4-v5-flows on node:sqlite, with each driver spelling injected for the "no such table" rejection only.

type Spelling = 'node' | 'api24' | 'api35';
const respell: Record<Spelling, (text: string, sql: string) => string> = {
  node: text => text,
  api24: (text, sql) => `${text} (code 1): , while compiling: ${sql}`,
  api35: (text, sql) => `${text} (Sqlite code 1 SQLITE_ERROR): , while compiling: ${sql}${OS_SUFFIX}`,
};

async function nodeFlows(spelling: Spelling) {
  const sql = realSQLite();
  sql.native.exec('PRAGMA foreign_keys = ON;');
  for (const statement of SQLITE_SCHEMA_STATEMENTS) if (!DEFERRED.includes(statement)) sql.native.exec(statement);
  await applyVersionedMigrations(sql.database);
  const errors: { order: number; sql: string; message: string; delivered: string; tables: string[] }[] = [];
  const original = sql.database.executeSql.bind(sql.database);
  (sql.database as unknown as { executeSql: typeof original }).executeSql = (async (text: string, values?: unknown[]) => {
    try { return await original(text, values as never); } catch (error) {
      const raw = String((error as { message?: unknown }).message);
      const delivered = /^no such table: /.test(raw) ? respell[spelling](raw, text) : raw;
      const tables = (sql.native.prepare("SELECT name FROM sqlite_master WHERE type = 'table' AND name LIKE 'installment_%' ORDER BY name").all() as { name: string }[])
        .map(row => row.name);
      errors.push({ order: sql.trace.length, sql: text, message: raw, delivered, tables });
      throw delivered === raw ? error : { message: delivered };
    }
  }) as typeof original;
  const database = manageSQLiteDatabase(sql.database);
  sql.resetTrace();
  try {
    const result = await runPhase1A3BFlows(database, async run => {
      const start = sql.trace.length; await run(); return sql.trace.slice(start).filter(entry => entry.write !== undefined).length;
    });
    const openTransaction = (sql.native as unknown as { isTransaction: boolean }).isTransaction;
    const finalTables = (sql.native.prepare("SELECT name FROM sqlite_master WHERE type = 'table' AND name LIKE 'installment_%' ORDER BY name").all() as { name: string }[])
      .map(row => row.name);
    return { result, errors, trace: [...sql.trace], openTransaction, finalTables };
  } finally { sql.native.close(); }
}

const reference = () => (JSON.parse(fs.readFileSync('docs/validacion-fase1a4b/node/results.json', 'utf8')) as { phase1a3b: { flows: Record<string, unknown> } }).phase1a3b.flows;

describe.each(['node', 'api24', 'api35'] as const)('phase 1a.4B r5 — v4-v5-flows with the %s spelling', spelling => {
  let run: Awaited<ReturnType<typeof nodeFlows>>;
  beforeAll(async () => { run = await nodeFlows(spelling); }, 300000);

  test('the whole flows result equals the current 1a.4B reference (version 4 and version 5)', () => {
    expect(JSON.parse(JSON.stringify(run.result))).toEqual(reference());
  });

  test('version 4: the table is absent, the guard query fails with the stable class and the delivered spelling', () => {
    const [guard, ...others] = run.errors;
    expect(guard!.sql).toBe(GUARD);
    expect(guard!.message).toBe(NODE_MESSAGE);
    expect(guard!.delivered).toBe(spelling === 'node' ? NODE_MESSAGE : spelling === 'api24' ? API24_HEAD + GUARD : API35_EXPECTED);
    expect(guard!.tables).not.toContain('installment_allocations');
    expect(errorClass(message(guard!.delivered))).toBe(STABLE);
    // The only other SQL error of the run: the first-round FOREIGN KEY refusal of resetSyntheticData (retried by design).
    expect(others.map(error => [error.sql.trim().split(/\s+/).slice(0, 3).join(' '), error.message])).toEqual([['DELETE FROM "accounts"', 'FOREIGN KEY constraint failed']]);
    expect((run.result as { version4Incompatible: unknown }).version4Incompatible).toEqual({ firstGuardedStep: 'editTerms', outcome: STABLE, stateUnchanged: true });
  });

  test('version 4: writes made before the guard are rolled back; nothing is committed; the next transaction commits', () => {
    const index = run.trace.findIndex(entry => entry.outcome === 'sql-error');
    const begin = run.trace.slice(0, index).map(entry => entry.sql.trim()).lastIndexOf('BEGIN IMMEDIATE;');
    expect(begin).toBeGreaterThanOrEqual(0);
    const inside = run.trace.slice(begin + 1, index);
    expect(inside.some(entry => /^(COMMIT|ROLLBACK)/.test(entry.sql.trim()))).toBe(false);
    // The error does NOT come before every write: the movement is upserted first, inside the same transaction.
    expect(inside.filter(entry => entry.write !== undefined).map(entry => entry.sql.trim().split(/\s+/).slice(0, 3).join(' ')))
      .toEqual(['UPDATE transactions SET', 'INSERT INTO transactions']);
    expect(run.trace[index + 1]!.sql.trim()).toBe('ROLLBACK;');
    const next = run.trace.slice(index + 2);
    expect(next.find(entry => /^(BEGIN|COMMIT|ROLLBACK)/.test(entry.sql.trim()))!.sql.trim()).toMatch(/^BEGIN( IMMEDIATE)?;$/);
    expect(next.some(entry => entry.sql.trim() === 'COMMIT;')).toBe(true);
    // stateUnchanged: true is recorded only after the probe compared the complete state (all tables, rowids, schema).
    expect(run.openTransaction).toBe(false);
  });

  test('version 5: the allocation tables exist, the whole flow runs, no missing-table error is raised', () => {
    const failed = run.trace.findIndex(entry => entry.outcome === 'sql-error');
    const migrated = run.trace.findIndex((entry, i) => i > failed && /^INSERT INTO schema_migrations VALUES \(5/.test(entry.sql.trim()));
    expect(migrated).toBeGreaterThan(failed);
    expect(run.errors.filter(error => error.order > migrated && /no such table/.test(error.delivered))).toEqual([]);
    expect(run.finalTables).toEqual(expect.arrayContaining(['installment_allocations', 'installment_plan_revisions']));
    const v5 = (run.result as { version5: { steps: Record<string, { writes: number }> } }).version5;
    expect(Object.keys(v5.steps)).toEqual(['editTerms', 'payment', 'deletePayment', 'deletePurchase']);
    expect(v5).toEqual(reference().version5);
  });
});
