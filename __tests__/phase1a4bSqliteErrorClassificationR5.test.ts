/** Real API 35 message: the failure stores the classified text and the raw driver text; both must be the same string. */
function api35Message() {
  const report = JSON.parse(fs.readFileSync('docs/validacion-fase1a4b/r4/android/api35/phase1a3b-flows/result.json', 'utf8')) as
    { failure: string; passed: boolean; config: { api: number; model: string } };
  expect([report.passed, report.config.api, report.config.model]).toEqual([false, 35, 'CRT-NX3']);
  const prefix = 'Error: Version 4 guarded step: other: ';
  const separator = ' | raw: ';
  const raw = report.failure.slice(report.failure.indexOf(separator) + separator.length);
  expect(report.failure).toBe(prefix + raw + separator + raw);
  return raw;
}

/** Real API 24 message of the r4 APK (diagnostic line), equal to the r3 stop. */
function api24Message() {
  const line = fs.readFileSync('docs/validacion-fase1a4b/r4/android/api24/phase1a3b-flows/logcat.txt', 'utf8')
    .split(/\r?\n/).filter(entry => entry.includes('PHASE1A3B_V4_GUARDED_STEP_ERROR:'));
  expect(line).toHaveLength(1);
  const r4 = JSON.parse(line[0]!.slice(line[0]!.indexOf('PHASE1A3B_V4_GUARDED_STEP_ERROR:') + 'PHASE1A3B_V4_GUARDED_STEP_ERROR:'.length)) as string;
  const r3 = JSON.parse(fs.readFileSync('docs/validacion-fase1a4b/r3/android/api24/phase1a3b-flows/result.json', 'utf8')) as { failure: string };
  expect(r3.failure).toBe('Error: Version 4 guarded step: other: ' + r4);
  return r4;
}

/** The r4 classifier, evaluated from the byte copy of the r4 derived probes (helpers it uses, nothing else). */
function r4Classifier() {
  const text = fs.readFileSync(R4_BASELINE, 'utf8');
  expect(sha256(text)).toBe(R4_PROBES_SHA256);
  const inventory = JSON.parse(fs.readFileSync('docs/validacion-fase1a4b/r4/authorization/inputs.sha256.json', 'utf8')) as { sources: Record<string, string> };
  expect(inventory.sources['scripts/phase1a4b/phase1a3bProbes.ts']).toBe(R4_PROBES_SHA256);
  const pick = (start: string, end: string) => {
    const from = text.indexOf(start);
    const to = text.indexOf(end, from);
    expect([start, from >= 0 && to > from]).toEqual([start, true]);
    expect(text.indexOf(start, from + 1)).toBe(-1);
    return text.slice(from, to + end.length);
  };
  const source = [pick('const json = ', ';\n'), pick('const errorText = ', ': json(error);\n'), pick('const RAISES = ', '];\n'),
    pick('export function missingTableName(', "return 'other: ' + text;\n}\n")].join('').replace(/^export /gm, '');
  const js = ts.transpileModule(`function build() {\n${source}\nreturn { missingTableName, errorClass };\n}`,
    { compilerOptions: { target: 7 /* ES2020 */ } }).outputText;
  // eslint-disable-next-line no-new-func
  return new Function(js + '\nreturn build();')() as { missingTableName: (text: string) => string | undefined; errorClass: (error: unknown) => string };
}

describe('phase 1a.4B r5 — reproduction of the r4 API 35 stop with the r4 classifier', () => {
  test('the real API 35 message, character for character', () => {
    const api35 = api35Message();
    expect(api35).toBe(API35_EXPECTED);
    expect(api35.includes('\r')).toBe(false);
    expect(api24Message()).toBe(API24_HEAD + GUARD);
  });

  test('the r4 classifier recognizes Node and API 24 but not API 35 (the r4 stop)', () => {
    const r4 = r4Classifier();
    expect(r4.errorClass(message(NODE_MESSAGE))).toBe(STABLE);
    expect(r4.errorClass(message(api24Message()))).toBe(STABLE);
    expect(r4.missingTableName(api35Message())).toBeUndefined();
    expect(r4.errorClass(message(api35Message()))).toBe('other: ' + api35Message());
    // Exactly the outcome recorded by the HONOR run.
    expect('Version 4 guarded step: ' + r4.errorClass(message(api35Message()))).toBe(
      JSON.parse(fs.readFileSync('docs/validacion-fase1a4b/r4/android/api35/phase1a3b-flows/result.json', 'utf8')).failure
        .replace(/^Error: /, '').split(' | raw: ')[0]);
  });
});

