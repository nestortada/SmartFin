'use strict';
// Phase 1a.4B r5: prepares a NEW isolated synthetic workspace from the audited r4 one (derived from
// scripts/phase1a4b/r4/prepare-android-r4.cjs). Copies files only: no adb, installs, dependency changes, database opens or
// compilation here.
// - Verifies r4 (attestation 97e1a907…, APK aa720dd0…, pinned in docs/validacion-fase1a4b/r4/authorization/apk-identity.json)
//   and every prepared r4 file against its attestation.
// - Verifies the r5 inventory and that the checkout matches every r4 pin except the corrected derived 1a.3B probes
//   (scripts/phase1a4b/phase1a3bProbes.ts, regenerated by derive-probes.cjs: r5 missing-table class, three spellings).
// - Incorporates ONLY that harness correction: phase1a3bProbes.ts, rewritten exactly as r1/r4 did ('../../src/' -> './src/').
//   Production, references (the five Node parts, regenerated here and compared byte for byte) and every other harness
//   file stay byte-identical to r4.
// - The r4 workspace was built (r4 run): build/, .gradle/ and .cxx/ are never copied, and any copied file modified after
//   the r4 attestation was written stops the preparation, so no build output or earlier APK can be reused.
// - Writes a new attestation (phase '1a.4B r5').
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '../../..');
const base = 'C:/sf-1a4b-r4-20261107';
const workspace = 'C:/sf-1a4b-r5-20261107';
const R4_ATTESTATION = '97e1a907b5a27442975938f70e4ce88b9f1be78cce7682f1f1c8f1d7cdb8831e';
const R4_APK = 'aa720dd012d2b19b10fab7f4acb843d096f246dfe25e98531797974a0842dd11';
const PROBES = 'scripts/phase1a4b/phase1a3bProbes.ts';
const PROBES_SHA256 = '508a88e5dc97265eec2b488d9e47dcf5c7852736dc742ad2d18f395fafb53b26';
const REFERENCE = 'docs/validacion-fase1a4b/node/results.json';
const REFERENCE_SHA256 = '1faa219207d86d95f7b55f3e3446243d3d6194bbd974e7018089e7acce41bd1b';
const sha = bytes => crypto.createHash('sha256').update(bytes).digest('hex');
const read = (dir, file) => fs.readFileSync(path.join(dir, file));
if (process.argv.length !== 2) throw Error('No arguments authorized');
if (fs.existsSync(workspace)) throw Error('Destination must be new; no overwrite or cleanup');

const inventory = JSON.parse(read(root, 'docs/validacion-fase1a4b/r5/authorization/inputs.sha256.json'));
if (inventory.phase !== '1a.4B r5') throw Error('Not the r5 inventory');
for (const [name, hash] of Object.entries(inventory.sources)) {
  if (name.startsWith('.claude/') || name.startsWith('.codex/')) continue; // guards: owner-managed, never altered here
  if (sha(read(root, name)) !== hash) throw Error('Reviewed input changed since the r5 inventory: ' + name);
}
if (sha(read(root, PROBES)) !== PROBES_SHA256) throw Error('Not the r5 derived probes');
if (sha(read(root, REFERENCE)) !== REFERENCE_SHA256) throw Error('1a.4B reference changed');

const identity = JSON.parse(read(root, 'docs/validacion-fase1a4b/r4/authorization/apk-identity.json'));
const attestation = read(base, 'source-fingerprints.json');
if (sha(attestation) !== R4_ATTESTATION || identity.attestationSha256 !== R4_ATTESTATION) throw Error('Unrecognized r4 attestation');
if (sha(read(base, 'android/app/build/outputs/apk/release/app-release.apk')) !== R4_APK || identity.sha256 !== R4_APK) throw Error('r4 APK mismatch');
const record = JSON.parse(attestation);
if (record.packageId !== 'com.smartfin.snapshot5b2.tests' || record.workspace !== base || record.phase !== '1a.4B r4') throw Error('r4 identity mismatch');
for (const name of Object.keys(record.hashes)) {
  if (name.includes('..') || path.isAbsolute(name)) throw Error('Invalid r4 path');
  if (sha(read(base, name)) !== record.hashes[name]) throw Error('r4 prepared source changed: ' + name);
}
const drift = Object.entries(record.originalHashes).filter(([name, hash]) => sha(read(root, name)) !== hash).map(([name]) => name);
if (JSON.stringify(drift) !== JSON.stringify([PROBES])) throw Error('Checkout differs from r4 beyond the derived probes: ' + drift.join(', '));

const attestedAt = fs.statSync(path.join(base, 'source-fingerprints.json')).mtimeMs;
const excluded = new Set(['node_modules', 'build', '.gradle', '.cxx', '.git', '.codex', '.claude', '.agents', 'docs']);
const lateFiles = [];
fs.cpSync(base, workspace, {recursive: true, filter(file) {
  const parts = path.relative(base, file).split(path.sep);
  const keep = !parts.some(part => excluded.has(part)) && !/\.(?:db|sqlite|sqlite3)(?:-|$)|\.jks$/i.test(file);
  if (keep) {
    const stat = fs.lstatSync(file);
    if (stat.isFile() && stat.mtimeMs > attestedAt + 1000) lateFiles.push(path.relative(base, file).split(path.sep).join('/'));
  }
  return keep;
}});
if (lateFiles.length) throw Error('Files written after the r4 attestation (build output?) were copied; remove ' + workspace + ' and review: ' + lateFiles.join(', '));
fs.symlinkSync(path.join(root, 'node_modules'), path.join(workspace, 'node_modules'), 'junction');
const r4Hashes = {...record.hashes};
record.workspace = workspace;
record.phase = '1a.4B r5';
record.r4 = {attestationSha256: R4_ATTESTATION, apkSha256: R4_APK, workspace: base};

const rewrite = bytes => bytes.toString().replaceAll("'../../src/", "'./src/")
  .replaceAll("'../phase6b/probes'", "'./phase6bProbes'").replaceAll("'../phase1a2/probes'", "'./phase1a2Probes'");
const probes = rewrite(read(root, PROBES));
if (/jest\.|reverseActivePaymentAllocations: async|requireNoActiveInstallmentAllocations: async/.test(probes)) throw Error('Neutralization found');
if (!probes.includes('export function missingTableName(') || !probes.includes('ANDROID_MISSING_TABLE_SPELLINGS') ||
    !probes.includes("{ code: ' (Sqlite code 1 SQLITE_ERROR): , while compiling: ', suffix: ', (OS error - 2:No such file or directory)' }") ||
    !probes.includes("check(editTerms === 'other: no such table: installment_allocations'") ||
    !probes.includes("check(json(await fullState(database)) === before, 'The failed version 4 step left changes');"))
  throw Error('r5 missing-table class or the strict version 4 checks are absent');
fs.writeFileSync(path.join(workspace, 'phase1a3bProbes.ts'), probes);
record.hashes['phase1a3bProbes.ts'] = sha(probes);
record.adaptations['phase1a3bProbes.ts'] = '1a.3B probes derived for 1a.4B (derive-probes.cjs: D6 guard, version 4 flows, r5 missing-table class: three observed spellings)';
record.originalHashes[PROBES] = PROBES_SHA256;

for (const [name, hash] of Object.entries(r4Hashes))
  if (name !== 'phase1a3bProbes.ts' && (record.hashes[name] !== hash || sha(read(workspace, name)) !== hash)) throw Error('r4 file changed: ' + name);
if (Object.keys(record.hashes).length !== Object.keys(r4Hashes).length) throw Error('Unexpected added file');
// The five Node parts, regenerated from the approved reference exactly as r1 did, must equal the carried files.
const reference = JSON.parse(read(root, REFERENCE));
const {probes: probes3a, atomicity, writes, unknown, restart} = reference.phase1a3a;
for (const [file, value] of [
  ['phase1a4bNodeExpected.json', reference.phase1a4b],
  ['phase1a4aNodeExpected.json', reference.phase1a4a],
  ['phase1a3bNodeExpected.json', reference.phase1a3b],
  ['phase1a3aNodeExpected.json', {probes: probes3a, atomicity, writes, unknown, restart}],
  ['phase1a2NodeExpected.json', {probes: reference.phase1a2.probes}],
]) if (read(workspace, file).toString() !== JSON.stringify({runtime: reference.runtime, ...value}, null, 2) + '\n') throw Error('Node part differs: ' + file);
const expected = JSON.parse(read(workspace, 'phase1a4bNodeExpected.json'));
if (expected.reversal.editAmount.observation.backupRevision !== 33 || expected.guards.deletePurchase.observation.backupRevision !== 25)
  throw Error('Corrected 1a.4B expectations missing');
const flows = JSON.parse(read(workspace, 'phase1a3bNodeExpected.json')).flows;
if (flows.version4Incompatible.outcome !== 'other: no such table: installment_allocations' || flows.version4Incompatible.stateUnchanged !== true ||
    JSON.stringify(Object.keys(flows.version5.steps)) !== JSON.stringify(['editTerms', 'payment', 'deletePayment', 'deletePurchase']))
  throw Error('Flows reference changed');
const manual = read(workspace, 'src/modules/transactions/useCases/saveManualTransaction.ts').toString();
if (!manual.includes('await reverseActivePaymentAllocations(') || !manual.includes('await requireNoActiveInstallmentAllocations(') ||
    !manual.includes('await recordInitialInstallmentRevision('))
  throw Error('1a.4B or 1a.4A step missing from the carried production code');
const walk = dir => fs.readdirSync(path.join(workspace, dir), {withFileTypes: true})
  .flatMap(entry => entry.isDirectory() ? walk(dir + '/' + entry.name) : [dir + '/' + entry.name]);
const users = walk('src').filter(file => /\.(tsx?|jsx?)$/.test(file) && /extraordinaryInstallmentPayment/i.test(read(workspace, file).toString()));
if (JSON.stringify(users) !== JSON.stringify(['src/modules/creditCards/useCases/extraordinaryInstallmentPayment.ts']))
  throw Error('The 1a.4B use case is referenced from production code: ' + users.join(', '));
const stillMismatched = Object.entries(record.originalHashes).filter(([name, hash]) => sha(read(root, name)) !== hash);
if (stillMismatched.length) throw Error('Checkout differs from attestation: ' + stillMismatched.map(([name]) => name).join(', '));

const encoded = JSON.stringify(record, null, 2);
fs.writeFileSync(path.join(workspace, 'source-fingerprints.json'), encoded);
fs.writeFileSync(path.join(workspace, 'android/app/src/main/assets/phase5b2-source-fingerprints.json'), encoded);
console.log(JSON.stringify({workspace, packageId: record.packageId, phase: record.phase, attestedFiles: Object.keys(record.hashes).length,
  changedFromR4: ['phase1a3bProbes.ts'], attestationSha256: sha(encoded), apkBuilt: false,
  expectations: {editAmount: 33, deletePurchase: 25, flowsVersion4: flows.version4Incompatible.outcome}}, null, 1));
